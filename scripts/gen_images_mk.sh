#!/bin/sh

set -eu

PREFIX="$1"
OWN="$2"
shift 2

ARCHS="amd64 arm64"

. "$(dirname "$0")/common.in"

get_arch_exclusions() {
	local df="$1"

	if [ -n "$df" ]; then
		grep '^# build:' "$df" 2>/dev/null \
			| grep -o '![a-z0-9_]*' \
			| sed 's/!//' \
			| tr '\n' ' ' \
			| sed 's/ *$//'
	fi
}

get_platform() {
	local excl=" $1 "
	local arch sep="" result=""

	for arch in $ARCHS; do
		case "$excl" in
		*" $arch "*) continue ;;
		esac
		result="${result}${sep}linux/${arch}"
		sep=","
	done
	echo "$result"
}

get_images() {
	cut -d' ' -f1 < "$1"
}

# print the images a Dockerfile builds on, one per FROM line, skipping
# scratch and the earlier stages of a multi-stage build. A template names
# our registry as @@PREFIX@@.
get_bases() {
	awk -v prefix="$PREFIX" '
		toupper($1) == "FROM" {
			img = ""
			for (i = 2; i <= NF; i++)
				if ($i !~ /^--/) { img = $i; break }
			gsub(/@@PREFIX@@/, prefix, img)
			if (img != "scratch" && !(img in stage))
				print img
			if (toupper($(NF - 1)) == "AS")
				stage[$NF] = 1
		}
	' "$1"
}

# the images a .tag-dirs entry depends on: those its Dockerfile builds on,
# or for an alias-only tag the tag it points to
get_from() {
	local dir="$1"

	if [ -d "$dir" ]; then
		get_bases "$(get_dockerfile "$dir")"
	else
		echo "$dir"
	fi
}

is_own() {
	grep -q "^${1#$PREFIX} " "$OWN"
}

get_3rd_party() {
	local tag= dir= from=

	while read tag dir; do
		for from in $(get_from "$dir"); do
			is_own "$from" || echo "$from"
		done
	done < "$OWN" | sort -uV
}

gen_image_files() {
	local dir="$1" df x
	shift

	df=$(get_dockerfile "$dir")

	(
	for x; do
		echo "$x"
	done

	# Extract files from COPY commands: skip --chown/... option flags and
	# emit every source, dropping the trailing destination. A COPY --from
	# reads another stage or image, not the build context.
	awk -v dir="$dir" '
		$1 == "COPY" {
			n = 0
			for (i = 2; i <= NF; i++) {
				if ($i ~ /^--from=/) next
				if ($i !~ /^--/) tok[++n] = $i
			}
			for (j = 1; j < n; j++) print dir "/" tok[j]
		}
	' "$df"

	# Files generated from .in templates, named without the suffix: the
	# rule wants the generated file, not the template it comes from.
	find "$dir" ! -type d -a -name '*.in' | sed -e 's|\.in$||'

	echo "$dir/Dockerfile"

	) | sed -e "s|^$PWD/||" -e "s|^./||" | sort -uV
}

key() {
	local x=
	for x; do
		echo "$x" | tr ':' '-'
	done
}

prefix() {
	local x=
	for x; do
		echo "\$(PREFIX)$(key $x)"
	done
}

puller() {
	local x=
	for x; do
		echo "pull-$(key $x)"
	done
}

# Sentinels for images built here. They carry $(SENTINEL_SUFFIX) so a local
# (BUILDER=) build cannot satisfy a publish target, or the other way about:
# the two record different artefacts under different names.
sentinel() {
	local x=
	for x; do
		x="$(echo "$x" | tr ':/' '-_')"
		echo "\$(B)/.image-$x\$(SENTINEL_SUFFIX)"
	done
}

aliases() {
	local x=
	for x; do
		x="$(echo "$x" | tr ':/' '-_')"
		echo "\$(B)/.alias-$x\$(SENTINEL_SUFFIX)"
	done
}

# Sentinel for an alias-only tag, holding the version its symlink resolves
# to. It records the state of the tree rather than an artefact either mode
# produced, so it takes no suffix and the two modes share it.
link() {
	local x=
	for x; do
		x="$(echo "$x" | tr ':/' '-_')"
		echo "\$(B)/.link-$x"
	done
}

# Sentinel for a third-party image, which is pulled rather than built. A pull
# is the same operation in either mode, so these take no suffix and the two
# modes share them.
pull_sentinel() {
	local x=
	for x; do
		x="$(echo "$x" | tr ':/' '-_')"
		echo "\$(B)/.image-$x"
	done
}

IMAGES=$(get_images "$OWN")
IMAGES_SHORT=$(echo "$IMAGES" | sed -e 's|:.*||' | sort -uV)
THIRD_PARTY=$(get_3rd_party)

cat <<EOT
# generated by $0
#
$(list_key_f IMAGES prefix $IMAGES_SHORT)
$(list_key_f PULLERS puller $(sort_uV $IMAGES_SHORT $IMAGES $THIRD_PARTY))
EOT

# THIRD_PARTY
#
for tag in $THIRD_PARTY; do
	s1="$(pull_sentinel "$tag")"
	k1="$(key "$tag")"
	d1="$(puller "$tag")"
	cat <<EOT

# $tag
#
.PHONY: $k1 $d1
$k1: $s1
$d1: $s1

$s1: \$(BUILD_SYS)
	\$(DOCKER) pull $tag
	touch \$@
EOT
done

# OWN
#
while read tag dir; do
	# Own base: its built image. Third-party base: its pulled image.
	s0=
	a0=
	for from in $(get_from "$dir"); do
		if is_own "$from"; then
			s0="$s0 $(sentinel "${from#$PREFIX}")"
			a0="$a0 $(aliases "${from#$PREFIX}")"
		else
			s0="$s0 $(pull_sentinel "$from")"
			a0="$a0 $(pull_sentinel "$from")"
		fi
	done

	if [ -d "$dir" ]; then
		df=$(get_dockerfile "$dir")
	else
		df=
		from=$dir
		dir=
	fi

	k1=$(key $tag)
	d1=$(puller $tag)
	s1=$(sentinel $tag)
	a1=$(aliases $tag)
	l1=$(link $tag)

	if [ -z "$dir" ]; then
		files="$a0 $l1"
	else
		# Base sentinels are intentionally absent here: they are a
		# gated prerequisite below (publish mode only), not an
		# unconditional build input.
		files="$(gen_image_files "$dir" '$(BUILD_SYS)')"
	fi

	excl=$(get_arch_exclusions "$df")
	platform=$(get_platform "$excl")

	cat <<EOT

# $tag
#
.PHONY: \$(PREFIX)$k1
\$(PREFIX)$k1: $a1

.PHONY: $d1
$d1:
	\$(DOCKER) pull \$(PREFIX)$tag

$s1: PLATFORM = $platform
$(list_target $s1 $files)
EOT

if [ -d "$dir" ]; then
	# In the normal (publish) mode the base images — own builds or
	# third-party pulls — are made first so each FROM reference resolves
	# from local storage. A dev (BUILDER=) build drops these edges to
	# stay single-target and lets buildx pull whatever base is published.
	cat <<EOT
ifeq (\$(WANTS_TAGS),1)
$(list_target $s1 $s0)
endif
EOT

	# With tags: push the multi-arch manifest and seed the registry cache.
	# Without tags: build for the host and load it untagged, recording the
	# image ID in the .local sentinel. A dev build leaves no persistent tag,
	# so docker image prune reclaims it; reference it via $(cat sentinel).
	cat <<EOT
ifeq (\$(WANTS_TAGS),1)
	\$(DOCKER_BUILD) \$(DOCKER_BUILD_OPT) --platform \$(PLATFORM) --push \\
		--cache-to type=inline \\
		--cache-from type=registry,ref=\$(PREFIX)$tag \\
		-t \$(PREFIX)$tag \\
		$dir
	touch \$@
else
	\$(DOCKER_BUILD) \$(DOCKER_BUILD_OPT) --load \\
		--iidfile \$@~ \\
		$dir
	mv \$@~ \$@
endif

$a1: $s1
	touch \$@
EOT
else
	# Alias-only tag: retag the registry manifest. Local builds are
	# untagged and single-target, so there is no tag to copy and the
	# alias resolves to a no-op.
	#
	# The link sentinel holds this tag's line from .tag-dirs, settled
	# so its mtime moves only when this link moves.
	cat <<EOT
ifeq (\$(WANTS_TAGS),1)
	\$(DOCKER_TAG) -t \$(PREFIX)$tag \$(PREFIX)$from
endif
	touch \$@

$a1: $s1
	touch \$@

$l1: \$(TAG_DIRS)
	\$(call settle,\$@,grep '^$tag ' \$<)
EOT
fi

done < "$OWN"

# shortcuts
#
for x in $IMAGES_SHORT; do

	k1=$(prefix $x)
	d1=$(puller $x)
	s1=$(sentinel $x)

	sub="$(grep "^$x:" "$OWN" | cut -d' ' -f1)"

	cat <<EOT

# $x
#
.PHONY: $k1
$k1: $s1

.PHONY: $d1
$(list_target_f $d1 puller $sub)

$(list_target_f $s1 aliases $sub)
	touch \$@
EOT
done
